def load(path):
    s = path.read_text(encoding="utf-8")
    return json.loads(s[s.index("{"):s.rindex("}")+1])

def jdump(obj):
    return json.dumps(obj, ensure_ascii=False, separators=(",", ":"))

def main():
    d = load(DEATHS)
    cols, rows = d["cols"], d["rows"]
    I = {k:i for i,k in enumerate(cols)}
    existing_ids = {r[I["id"]] for r in rows}
    existing_pair = {(r[I["name"]], r[I["date"]]) for r in rows}
    links = load(LINKS)

    stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
    shutil.copy2(DEATHS, DATA / f"deaths.before-round3-{stamp}.js")
    shutil.copy2(LINKS, DATA / f"source-links.before-round3-{stamp}.js")

    added_rows, added_links = [], {}
    for p in NEW:
        if p["id"] in existing_ids or (p["name"], p["date"]) in existing_pair:
            print("跳过（已存在）:", p["name"]); continue
        base = {k:None for k in cols}
        base.update({k:v for k,v in p.items() if k in cols and k != "link"})
        base.setdefault("nameOrig", p["name"])
        base["verified"] = "manual"
        added_rows.append([base.get(k) for k in cols])
        added_links[p["id"]] = p["link"]
        existing_ids.add(p["id"]); existing_pair.add((p["name"], p["date"]))

    # 廖建文时区澄清：补港交所公告来源、修正 facts 表述（date 保持北京时间 11-23）
    fixed = 0
    for r in rows:
        if r[I["id"]] == "20261123-liao-jianwen":
            r[I["source"]] = "长江商学院美西校友会 / 港交所公告（百融智能）"
            facts = r[I["facts"]] or []
            facts = [f for f in facts if "逝世" not in f]
            facts.append("美西时间 2026 年 11 月 22 日 12 时 40 分在洛杉矶逝世（北京时间 11 月 23 日 4 时 40 分）")
            r[I["facts"]] = facts
            bio = r[I["bio"]] or ""
            if "美西" not in bio:
                bio = bio.replace("2026 年 11 月 23 日凌晨 4 时 40 分逝世。",
                                  "美西时间 2026 年 11 月 22 日 12 时 40 分在洛杉矶逝世（北京时间 11 月 23 日 4 时 40 分）。")
                r[I["bio"]] = bio
            lk = links.get("20261123-liao-jianwen") or []
            if not any("港交所" in x.get("n","") for x in lk):
                lk.append({"n":"港交所公告（百融智能，腾讯新闻转述）","u":"https://news.qq.com/rain/a/20261125A0BI3G00"})
            links["20261123-liao-jianwen"] = lk
            fixed = 1

    if not added_rows and not fixed:
        print("没有需要变更的记录"); return

    allrows = rows + added_rows
    allrows.sort(key=lambda r: r[I["date"]], reverse=True)
    DEATHS.write_text(
        "// 人物数据：每天离世的世界名人讣告档案（列式压缩）\n"
        f"window.DEATHS_DATA = {jdump({'cols':cols,'rows':allrows})};\n",
        encoding="utf-8")

    links.update(added_links)
    LINKS.write_text(f"window.SOURCE_LINKS = {jdump(links)};\n", encoding="utf-8")

    print(f"新增 {len(added_rows)} 条，修正 {fixed} 条")
    print(f"主表 {len(rows)} → {len(allrows)} 条 | 新增来源链接 {len(added_links)} 条")
    print(f"备份：deaths.before-round3-{stamp}.js / source-links.before-round3-{stamp}.js")

if __name__ == "__main__":
    main()
